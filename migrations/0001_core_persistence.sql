-- Core Order and Inventory persistence foundation (issue #21).
-- Applied by the versioned migration runner; do not execute on API startup.

CREATE TABLE schema_migrations (
    version VARCHAR(128) PRIMARY KEY,
    checksum CHAR(64) NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    category VARCHAR(80) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT products_sku_normalized CHECK (sku = upper(btrim(sku))),
    CONSTRAINT products_name_nonblank CHECK (length(btrim(name)) > 0),
    CONSTRAINT products_category_nonblank CHECK (length(btrim(category)) > 0)
);

CREATE TABLE inventory_balances (
    product_id BIGINT PRIMARY KEY REFERENCES products(product_id),
    on_hand BIGINT NOT NULL DEFAULT 0 CHECK (on_hand >= 0),
    reserved BIGINT NOT NULL DEFAULT 0 CHECK (reserved >= 0 AND reserved <= on_hand),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reservations (
    reservation_id UUID PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    saga_id VARCHAR(128) NOT NULL,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('reserved', 'released', 'committed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT reservations_saga_product_unique UNIQUE (saga_id, product_id)
);

CREATE INDEX reservations_product_status_idx
    ON reservations (product_id, status);

CREATE TABLE inventory_movements (
    movement_id UUID PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    movement_type VARCHAR(32) NOT NULL CHECK (
        movement_type IN (
            'opening_balance',
            'receipt',
            'adjustment',
            'reservation_created',
            'reservation_released',
            'reservation_committed'
        )
    ),
    quantity_delta_on_hand BIGINT NOT NULL DEFAULT 0,
    quantity_delta_reserved BIGINT NOT NULL DEFAULT 0,
    reference VARCHAR(256),
    idempotency_key VARCHAR(128),
    reservation_id UUID REFERENCES reservations(reservation_id),
    order_id BIGINT,
    saga_id VARCHAR(128),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT inventory_movements_nonzero_delta CHECK (
        quantity_delta_on_hand <> 0 OR quantity_delta_reserved <> 0
    )
);

CREATE INDEX inventory_movements_product_time_idx
    ON inventory_movements (product_id, occurred_at DESC, movement_id);

CREATE INDEX inventory_movements_reservation_idx
    ON inventory_movements (reservation_id)
    WHERE reservation_id IS NOT NULL;

CREATE TABLE idempotency_records (
    idempotency_record_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    scope VARCHAR(128) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    response JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT idempotency_scope_key_unique UNIQUE (scope, idempotency_key)
);

CREATE TABLE orders (
    order_id BIGINT PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount > 0),
    saga_id VARCHAR(128) NOT NULL UNIQUE,
    reservation_id UUID REFERENCES reservations(reservation_id),
    payment_id VARCHAR(128),
    status VARCHAR(32) NOT NULL CHECK (
        status IN (
            'pending',
            'processed',
            'payment_declined',
            'inventory_rejected',
            'failed',
            'compensation_incomplete'
        )
    ),
    failure_category VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT orders_total_matches_quantity CHECK (
        total_amount = unit_price * quantity
    )
);

CREATE INDEX orders_product_created_idx ON orders (product_id, created_at DESC);

-- The movement journal is append-only. A correction must be represented by
-- another movement; historical facts are never rewritten or deleted.
CREATE FUNCTION reject_inventory_movement_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'inventory_movements is append-only';
END;
$$;

CREATE TRIGGER inventory_movements_no_update
    BEFORE UPDATE OR DELETE ON inventory_movements
    FOR EACH ROW EXECUTE FUNCTION reject_inventory_movement_mutation();
